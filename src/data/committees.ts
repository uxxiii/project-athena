function generatePortfolios(committeeId: string): Committee["portfolios"] {
  const customPortfolios = CUSTOM_PORTFOLIOS[committeeId];
  const portfolioCount = customPortfolios?.length ?? PORTFOLIO_COUNT;

  return Array.from({ length: portfolioCount }, (_, i) => {
    const customPortfolio = customPortfolios?.[i];

    return {
      id: `${committeeId}-portfolio-${i + 1}`,
      name: customPortfolio?.name ?? `Delegate ${i + 1}`,
      group: customPortfolio?.group,
      team: customPortfolio?.team,
    };
  });
}

